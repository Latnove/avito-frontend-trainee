import type { ItemUpdateIn } from '@/entities/ad'

export const formatParams = (params: Record<string, unknown>) => {
  return Object.entries(params || {})
    .filter(([, value]) => value !== undefined && value !== null && value !== '')
    .map(([key, value]) => `${key}: ${value}`)
    .join(', ')
}

export const buildDescriptionPrompt = (item: ItemUpdateIn) => {
  const paramsText = formatParams(item.params as Record<string, unknown>)

  return `
	Ты помогаешь написать объявление для продажи своей вещи (как на Авито)

	Пиши от первого лица, простым и естественным языком

	Используй ТОЛЬКО те факты, которые есть в данных.
	Если ЕСТЬ ОПИСАНИЕ: тебе необходимо УЛУЧШИТЬ ЕГО СОХРАНИВ СУТЬ - ДОБАВИТЬ ПОБОЛЬШЕ ИНФОРМАЦИИ БЕЗ ВОДЫ
	Строго запрещено:
	придумывать срок использования (например: "пользовался год")
	придумывать состояние (например: "как новый"), если это не указано
	добавлять информацию, которой нет

	Если какие-то данные выглядят странно или нереалистично — не акцентируй на них внимание и не употребляй в описании

	Данные:
	Категория: ${item.category}
	Название: ${item.title}
	Цена: ${item.price}
	Характеристики: ${paramsText || 'не указаны'}
	Описание: ${item.description?.trim() || 'отсутствует'}

	Требования:
	- текст должен быть живым, как у обычного человека
	- избегай странных формулировок (например: "миллиметраж", "двигун" - это плохо)
	- пиши коротко и по делу
	- без переносов 
	- не более 1000 символов

	Структура:
	1. Что продаётся
	2. Основные характеристики - затронуть кратко
	3. Короткое преимущество (без выдумок) + описание

	Верни только текст объявления без оформления
	`
}

export const buildPricePrompt = (item: ItemUpdateIn) => {
  const paramsText = formatParams(item.params as Record<string, unknown>)

  return `
Ты помогаешь пользователю определить цену для продажи своей вещи (как на Авито).

Пиши ТОЛЬКО на русском языке.

Используй только предоставленные данные. Ничего не выдумывай.

Данные:
Название: ${item.title}
Категория: ${item.category}
Характеристики: ${paramsText || 'не указаны'}
Описание: ${item.description?.trim() || 'отсутствует'}

Требования:
- предложи диапазоны цен:
  - быстрая продажа
  - средняя цена
  - максимальная цена
- пиши коротко и понятно
- текст должен быть как для обычного пользователя

ФОРМАТ ОТВЕТА (СТРОГО ОБЯЗАТЕЛЕН):

price: <число>, text: <текст>

Где:
- price — средняя рекомендованная цена (ТОЛЬКО число, без валюты, без пробелов)
- text — объяснение с диапазонами цен

ПРИМЕР ПРАВИЛЬНОГО ОТВЕТА:

price: 120000, text: Средняя цена: 110 000 – 130 000 ₽ — нормальное состояние. От 140 000 ₽ — отличное состояние. 90 000 – 105 000 ₽ — быстрая продажа.

ЗАПРЕЩЕНО:
- использовать JSON
- добавлять переносы строк
- писать что-либо до или после ответа
- менять формат строки

Ответ должен быть одной строкой строго в указанном формате.
`
}
